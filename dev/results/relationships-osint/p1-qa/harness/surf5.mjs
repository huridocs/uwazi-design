import { launch, pickCollection } from "./lib.mjs";
import { compareAll, expandAll } from "./cmp.mjs";
const T = "Sushila Karki sworn in as interim prime minister";
const { b, p, errs } = await launch();
await pickCollection(p, /Nepal protests/);
await p.getByPlaceholder(/Search title/).fill("Sushila Karki sworn in");
await p.keyboard.press("Enter");
await p.waitForTimeout(1200);
await p.evaluate((t) => document.querySelector(`button[aria-label="Preview ${t}"]`).click(), T);
await p.waitForTimeout(1500);
await p.getByRole("tab", { name: /^Relationships/ }).last().click();
await p.waitForTimeout(1000);
await expandAll(p);
const n0 = await p.locator('[data-component="EvidenceStatus"]').count();
console.log("preview evidence buttons", n0);
const r = await compareAll(p, "nepal", T, { max: 33 });
console.log("LIBRARY PREVIEW: buttons", r.n, "mismatch", r.mismatches.length, "focusFail", r.focusFail.length, JSON.stringify(r.mismatches).slice(0,500));
await p.locator('[data-component="EvidenceStatus"]').nth(2).click();
await p.waitForTimeout(500);
await p.screenshot({ path: "surf5-library-preview-card.png" });
console.log("dialog box", JSON.stringify(await p.locator('[data-component="RefEvidenceCard"]').boundingBox()));
await p.keyboard.press("Escape");
await p.waitForTimeout(300);
console.log("preview still open after Esc:", await p.getByRole("tab", { name: /^Relationships/ }).last().isVisible());
console.log(errs);
await b.close();
