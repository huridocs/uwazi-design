"""Per-volley sync check. Reads working.pkl (written by build_seed.py), writes sync-check.json and sync-check.md."""
import pickle, json, os, statistics, collections, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from timeparse import DAY0, T2200
from datetime import timedelta
HERE = os.path.dirname(os.path.abspath(__file__))
w = pickle.load(open(os.path.join(HERE, "working.pkl"), "rb"))
recs, vs, med, iv, moments = w["recs"], w["vol_stats"], w["vol_median"], w["intervals"], w["moments"]
hms = lambda s: (DAY0 + timedelta(seconds=round(s))).strftime("%H:%M:%S")
f1 = lambda x: f"{x:+.1f}".replace("+-", "-")

rows = []
for n in range(1, 13):
    s = vs[n]
    rows.append(dict(volley=n, annotations=s["n"], median=hms(s["median"]), min_off=round(s["min"], 1), max_off=round(s["max"], 1), spread=round(s["spread"], 1),
                     stdev=round(s["stdev"], 2), mad=round(s["mad"], 2), within1=s["within1"], within2=s["within2"],
                     outliers=[(rid, round(d, 1)) for rid, d in s["outliers"]]))
gaps = [(n, iv[n]) for n in range(2, 13)]
long_gaps = [(n, g) for n, g in gaps if g > 60]
# per-recording flagged lists
mism = []
for r in recs:
    if "title-mismatch" in r["flags"]:
        mism.append(dict(id=r["id"], kind=r["kind"], index=r["index"], title=hms(r["title_secs"]), implied=hms(r["first_implied"]), diff=round(r["first_implied"] - r["title_secs"], 1)))
drift = [dict(id=r["id"], kind=r["kind"], anchors=r["anchors"], spread=round(r["spread"], 1)) for r in recs if "drift" in r["flags"]]
outl = [dict(id=r["id"], kind=r["kind"], residual=round(r["residual"], 1)) for r in recs if "outlier" in r["flags"]]
notes = [dict(id=r["id"], note=r["clock_note"], error=r["clock_err"], residual=(round(r["residual"], 1) if r["residual"] is not None else None),
              annotations=len([a for a in r["ann"] if a.get("residual") is not None])) for r in recs if r["clock_note"]]
# how many recordings give a volley, by kind
cov = collections.Counter()
for r in recs:
    for n in {a["volley"] for a in r["ann"] if a["type"] == "volley" and a["qualifier"] is None}:
        cov[(r["kind"], n)] += 1
# residual distribution over all unqualified volley annotations
allres = [a["residual"] for r in recs for a in r["ann"] if a.get("residual") is not None]
res_summary = dict(n=len(allres), within1=sum(abs(x) <= 1 for x in allres), within2=sum(abs(x) <= 2 for x in allres), over2=sum(abs(x) > 2 for x in allres),
                   median_abs=round(statistics.median([abs(x) for x in allres]), 2), p95_abs=round(sorted(abs(x) for x in allres)[int(0.95 * len(allres))], 1))
# by kind: median absolute residual
by_kind = collections.defaultdict(list)
for r in recs:
    for a in r["ann"]:
        if a.get("residual") is not None: by_kind[r["kind"]].append(a["residual"])
kind_summary = {k: dict(n=len(v), median=round(statistics.median(v), 2), median_abs=round(statistics.median([abs(x) for x in v]), 2), over2=sum(abs(x) > 2 for x in v)) for k, v in by_kind.items()}
# comparison with the first/last official times
first_map = moments.get("moment:20171001t220527-first-shots")
fs = hms(first_map["secs"]) if first_map else None
nyt_gap_count = len(long_gaps)
out = dict(volleys=rows, intervals=[dict(volley=n, seconds=round(g, 1)) for n, g in gaps], intervals_over_60=[dict(volley=n, seconds=round(g, 1)) for n, g in long_gaps],
           residuals=res_summary, by_kind=kind_summary, title_mismatch=mism, drift=drift, outliers=outl, clock_notes=notes,
           first_shots_map=fs, volley1=hms(med[1]), volley12=hms(med[12]))
json.dump(out, open(os.path.join(HERE, "sync-check.json"), "w"), indent=1)

L = []
A = L.append
A("# Vegas seed: sync check\n")
A("Generated by `data/sync_report.py` from the map's own annotations (nothing external except the comparisons in sections 3 and 4). Times are Las Vegas local time (PDT) on 1 October 2017. A volley annotation is a line such as `10:13:31 10th Volley Begins :02` on a recording: the clock time of the start of the volley, and the offset in the video.\n")
nq = sum(1 for r in recs for x in r["ann"] if x["qualifier"]); nqv = sum(1 for r in recs for x in r["ann"] if x["qualifier"] and x["type"] == "volley")
A(f"Annotations marked partial on the map (for example `(last :02)` or `(:03 in)`) are left out of the volley statistics: the video starts inside the volley, so the clock time is not the volley's start. {nq} annotations are marked this way, {nqv} of them volleys; the statistics below use the other {sum(x['annotations'] for x in rows)} volley annotations.\n")
A("## 1. Spread of each volley across recordings\n")
A("Offset = a recording's annotated clock time minus the volley's median. An outlier is more than 2 seconds from the median.\n")
A("| Volley | Recordings | Median | Min offset (s) | Max offset (s) | Spread (s) | Std dev (s) | Median abs dev (s) | Within 1 s | Within 2 s | Outliers (> 2 s) |")
A("|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---|")
for x in rows:
    o = ", ".join(f"`{i}` {f1(d)} s" for i, d in x["outliers"]) or "none"
    A(f"| {x['volley']} | {x['annotations']} | {x['median']} | {f1(x['min_off'])} | {f1(x['max_off'])} | {x['spread']:.0f} | {x['stdev']:.2f} | {x['mad']:.2f} | {x['within1']} | {x['within2']} | {o} |")
r_ = res_summary
A(f"\nAcross all {r_['n']} volley annotations: {r_['within1']} ({r_['within1']/r_['n']*100:.0f}%) are within 1 s of their volley's median, {r_['within2']} ({r_['within2']/r_['n']*100:.0f}%) within 2 s, {r_['over2']} are further. Median absolute offset {r_['median_abs']} s; 95th percentile {r_['p95_abs']} s.\n")
A("By kind of recording (offset from the volley median, all volleys):\n")
A("| Kind | Annotations | Median offset (s) | Median abs offset (s) | Over 2 s |")
A("|---|---:|---:|---:|---:|")
for k, v in sorted(kind_summary.items()):
    A(f"| {k} | {v['n']} | {f1(v['median'])} | {v['median_abs']} | {v['over2']} |")
A("")
A("## 2. Interval between volley starts\n")
A("| Volleys | Interval (s) |")
A("|---|---:|")
for n, g in gaps:
    A(f"| {n-1} to {n} | {g:.0f} |")
A(f"\nIntervals over one minute: {', '.join(f'{n-1} to {n} ({g:.0f} s)' for n, g in long_gaps) or 'none'}.\n")
A("## 3. Comparison with the New York Times analysis\n")
A("What the NYT published (read in the reporter's thread and in summaries; the article's burst times were not available): twelve main bursts, three intervals of more than a minute, a burst of about 40 seconds below the gunman's position, and six clock sources within a 3-second window for the start.\n")
A("| Check | NYT | Map | Result |")
A("|---|---|---|---|")
A("| Number of bursts | 12 | 12 numbered volleys, each annotated in 19 to 53 recordings | Match |")
A(f"| Intervals over one minute | 3 | {nyt_gap_count} ({', '.join(f'{n-1} to {n}' for n, g in long_gaps)}) | {'Match' if nyt_gap_count == 3 else 'Differs'} |")
A(f"| Start of the attack | 3-second window across six clock sources | 'First shots' annotated at {fs} in 12 recordings (spread 0 s); volley 1 at {hms(med[1])} | Not comparable: the NYT gives no clock time in what was read |")
A("| One burst of about 40 s below the gunman | Yes (no clock time given) | One cluster of 'down-the-hall' annotations at about 22:10:37 in 7 recordings, no duration | Possible match, not established |")
A("")
A("## 4. Comparison with the official times (from summaries, not read at source)\n")
A("| Event | Official time | Map | Difference |")
A("|---|---|---|---|")
A(f"| First shots | about 22:05 (CCTV at the venue) | 'first shots' annotation {fs}; first automatic burst (volley 1) {hms(med[1])} | The first shots fall inside the official minute. Volley 1 follows them by {round(med[1]-first_map['secs'])} s |")
A(f"| Last shots | about 22:15 (body-worn camera) | volley 12 starts {hms(med[12])} | The start of the last volley is inside the official minute; its end is not annotated on the map |")
A("\nThe official times are given to the minute, so a difference of up to 60 s is within their precision. The Criminal Investigative Report may give times to the second; read it before using this comparison.\n")
A("## 5. Recordings the check flags\n")
A("### 5.1 Title time differs from the time implied by the first annotation (more than 2 s)\n")
tested = sum(1 for r in recs if r["first_implied"] is not None and r["title_secs"] is not None and r["t"]["precision"] == "second")
A(f"{len(mism)} of {tested} recordings that have both values (title time to the second, and at least one annotation with an offset). Title time is the clock in the map title. Implied time is the annotation's clock minus its offset in the video. The other {tested-len(mism)} agree within 2 s.\n")
A("| Recording | Kind | Index in folder | Title time | Implied start | Difference (s) |")
A("|---|---|---:|---|---|---:|")
for m in sorted(mism, key=lambda x: x["diff"]):
    A(f"| `{m['id']}` | {m['kind']} | {m['index']} | {m['title']} | {m['implied']} | {f1(m['diff'])} |")
A("\n### 5.2 Anchors inside one recording disagree by more than 2 s (drift)\n")
A("The implied start (annotation clock minus offset) should be the same for every annotation of one recording. Where it is not, the recording may be cut, sped up, or annotated inconsistently.\n")
A("| Recording | Kind | Anchors | Spread of implied start (s) |")
A("|---|---|---:|---:|")
for m in sorted(drift, key=lambda x: -x["spread"]):
    A(f"| `{m['id']}` | {m['kind']} | {m['anchors']} | {m['spread']:.0f} |")
A("\n### 5.3 Recordings with a volley time more than 2 s from the median\n")
A("| Recording | Kind | Median offset of its volley annotations (s) |")
A("|---|---|---:|")
for m in outl:
    A(f"| `{m['id']}` | {m['kind']} | {f1(m['residual'])} |")
A("\n### 5.4 Camera clock errors noted on the map\n")
A("The map says these body camera time stamps run ahead of real time. The offset column shows whether the annotated times already include the correction (offset near 0) or not (offset near the stated error).\n")
A("| Recording | Note on the map | Stated error (s) | Median offset from volley medians (s) | Volley annotations |")
A("|---|---|---:|---:|---:|")
for m in notes:
    A(f"| `{m['id']}` | {m['note']} | {m['error']} | {f1(m['residual']) if m['residual'] is not None else 'none'} | {m['annotations']} |")
A("")
open(os.path.join(HERE, "sync-check.md"), "w").write("\n".join(L))
print("\n".join(L[:70]))
