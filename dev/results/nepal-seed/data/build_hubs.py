#!/usr/bin/env python3
"""Write hubs.json beside this script: the references that form one n-ary relation (a hub), by seed reference id.

Reads references.json and entities.json. Edits neither. Run after merge.py (reference ids are the merge's output):
    python3 -I build_hubs.py            write hubs.json
    python3 -I build_hubs.py --check    exit 1 when hubs.json is not what this run would write

A hub is one fact with several parties, seen from the record that anchors it:
  claim-stance    a claim's `supports` links, and (a separate hub) its `disputes` links; members are Source records
  event-involved  an event's `involved` links; members are the people and organisations involved

A group is a hub only with 2 or more distinct member records. A group with one member stays a plain reference.
Each reference carries one hub id (a type belongs to one kind, a claim's side to one hub), so groups cannot overlap;
the script fails if they do. README section "Hubs" has the shape and the reasoning.
"""
import json, os, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "hubs.json")

R = json.load(open(f"{HERE}/references.json"))
E = {e["id"]: e for e in json.load(open(f"{HERE}/entities.json"))}

# kind -> (relation types, which end anchors the hub, anchor template, member templates, hub id for (anchor, type))
KINDS = {
    "claim-stance": {
        "types": ("supports", "disputes"),
        "anchor_end": "to", "member_end": "from",
        "anchor_template": "claim", "member_templates": {"source"},
        "id": lambda anchor, typ: f"hub-claim-{anchor.split(':', 1)[1]}-{typ}",
        "about": "One claim and the sources that take one position on it. The claim's supporting sources are one hub "
                 "and its disputing sources another; both name the claim as their anchor.",
    },
    "event-involved": {
        "types": ("involved",),
        "anchor_end": "from", "member_end": "to",
        "anchor_template": "event", "member_templates": {"person", "organisation"},
        "id": lambda anchor, typ: f"hub-event-{anchor.split(':', 1)[1]}",
        "about": "One event and the people and organisations recorded as involved in it.",
    },
}
KIND_OF_TYPE = {t: k for k, v in KINDS.items() for t in v["types"]}

errors = []
def fail(msg): errors.append(msg)

# group the references: (kind, anchor, relation type) -> [reference]
groups = collections.OrderedDict()
for r in R:
    kind = KIND_OF_TYPE.get(r["type"])
    if not kind:
        continue
    k = KINDS[kind]
    anchor, member = r[k["anchor_end"]], r[k["member_end"]]
    if anchor not in E or member not in E:
        fail(f"{r['id']}: an end is not a record"); continue
    if E[anchor]["template"] != k["anchor_template"]:
        fail(f"{r['id']}: {kind} anchor {anchor} is a {E[anchor]['template']}, not a {k['anchor_template']}")
    if E[member]["template"] not in k["member_templates"]:
        fail(f"{r['id']}: {kind} member {member} is a {E[member]['template']}")
    groups.setdefault((kind, anchor, r["type"]), []).append(r)

hubs, seen_ref, seen_id = [], {}, {}
for (kind, anchor, typ), refs in groups.items():
    members = list(dict.fromkeys(r[KINDS[kind]["member_end"]] for r in refs))
    if len(members) < 2:
        continue
    hid = KINDS[kind]["id"](anchor, typ)
    if hid in seen_id: fail(f"hub id {hid} is made twice")
    seen_id[hid] = True
    for r in refs:
        if r["id"] in seen_ref: fail(f"{r['id']} is in {seen_ref[r['id']]} and {hid}")
        seen_ref[r["id"]] = hid
    hubs.append({"id": hid, "kind": kind, "anchor": anchor, "relationType": typ,
                 "memberIds": members, "refIds": [r["id"] for r in refs]})

# Privacy (CONTRACT.md): no member is a casualty, a minor or a withheld identity; nothing here is a phone or an e-mail.
for h in hubs:
    for m in h["memberIds"]:
        p = E[m].get("properties", {})
        if E[m]["template"] == "casualty" or p.get("identity_status") == "withheld" or (isinstance(p.get("age"), int) and p["age"] < 18):
            fail(f"{h['id']}: member {m} is a casualty, a minor or a withheld identity")
        if "@" in E[m]["title"]:
            fail(f"{h['id']}: member {m} title has an e-mail address")

hubs.sort(key=lambda h: h["id"])
doc = {
    "version": 1,
    "about": "References that form one n-ary relation, by seed reference id. Generated by data/build_hubs.py; do not edit.",
    "kinds": {k: {"relationTypes": list(v["types"]), "anchor": v["anchor_template"], "members": sorted(v["member_templates"]),
                  "about": v["about"]} for k, v in KINDS.items()},
    "hubs": hubs,
}
if errors:
    print("\n".join(errors)); sys.exit(1)
text = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
if "--check" in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    print("hubs.json is current" if cur == text else "hubs.json is stale: rerun build_hubs.py")
    sys.exit(0 if cur == text else 1)
open(OUT, "w").write(text)
c = collections.Counter(h["kind"] for h in hubs)
by_type = collections.Counter((h["kind"], h["relationType"]) for h in hubs)
print(f"{len(hubs)} hubs over {len(seen_ref)} references of {len(R)}")
for k, n in sorted(by_type.items()): print(f"  {k[0]} / {k[1]}: {n} hubs, {sum(len(h['refIds']) for h in hubs if (h['kind'], h['relationType']) == k)} references")
