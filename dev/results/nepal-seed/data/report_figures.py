#!/usr/bin/env python3
"""Write ../figures-report.md: counts, disagreements by (unit, scope, as_of), the flagged and skipped claims.
Run after merge.py."""
import collections, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ents = json.load(open(f"{HERE}/entities.json"))
rev = json.load(open(f"{HERE}/figures-review.json"))
figs = [e for e in ents if e["template"] == "claim" and e["properties"].get("figure") is not None]
cnt = lambda k: collections.Counter(e["properties"][k] for e in figs)
def fmt(n): return f"{n:,}"
L = ["# Claim figures: counts, disagreements, uncertain cases", "",
     "Generated by `data/report_figures.py` from `entities.json`. Decisions: `data/build_figures.py`.", "",
     f"- Claims with a structured figure: **{len(figs)}** of {sum(1 for e in ents if e['template']=='claim')} claims "
     f"({sum(1 for e in figs if e['properties'].get('claim_type')=='casualty-figure')} of the "
     f"{sum(1 for e in ents if e['template']=='claim' and e['properties'].get('claim_type')=='casualty-figure')} casualty-figure claims, "
     f"plus {sum(1 for e in figs if e['properties'].get('claim_type')!='casualty-figure')} counts and amounts typed other).",
     f"- Casualty-figure claims left without a figure: {len(rev['skipped'])} (not counts, listed below).",
     "", "## By unit", "", "| Unit | Claims |", "|---|---|"]
L += [f"| {u} | {n} |" for u, n in cnt("unit").most_common()]
L += ["", "Unit `other` by detail: " + "; ".join(f"{d} {n}" for d, n in collections.Counter(e["properties"].get("unit_detail") for e in figs if e["properties"]["unit"] == "other").most_common()), ""]
L += ["## By qualifier and as-of basis", "", "| Qualifier | Claims |", "|---|---|"] + [f"| {u} | {n} |" for u, n in cnt("qualifier").most_common()]
L += ["", "| as_of basis | Claims |", "|---|---|"] + [f"| {u} | {n} |" for u, n in cnt("as_of_basis").most_common()]
L += ["", "`stated`: the date is in the statement. `derived`: taken from the event or period the statement names. `published`: only the publication date is known and is used as a stand-in; treat such as_of values as upper bounds. `unknown`: no as_of.", ""]
g = collections.defaultdict(list)
for e in figs:
    p = e["properties"]
    if p.get("as_of"): g[(p["unit"], p.get("unit_detail") or "", p["scope"], p["as_of"])].append(e)
dis = {k: v for k, v in g.items() if len({x["properties"]["figure"] for x in v}) > 1}
L += ["## Disagreements: same unit, scope and as_of, different figures", "",
      f"The figures fall into {len(g)} groups by unit, scope and as_of date ({sum(1 for v in g.values() if len(v) > 1)} hold two or more claims); {len(dis)} groups hold different figures. "
      "Within a date, a later time of day usually explains the difference (an update, not a conflict); the time column shows it.", ""]
for k, v in sorted(dis.items(), key=lambda kv: (kv[0][3], kv[0][0], kv[0][2])):
    L.append(f"### {k[0]}{' (' + k[1] + ')' if k[1] else ''}, {k[2]}, as of {k[3]}")
    L += ["", "| Figure | Qualifier | Time | Claim |", "|---|---|---|---|"]
    for e in sorted(v, key=lambda x: (x["properties"]["figure"], x["id"])):
        p = e["properties"]
        L.append(f"| {fmt(p['figure'])} | {p['qualifier']} | {p.get('as_of_time','')} | `{e['id'][6:]}` |")
    L.append("")
# series: national killed, by as_of
L += ["## National death toll over time (unit killed, scope national, from September 2025)", "", "| as_of | Figures | Basis |", "|---|---|---|"]
ser = collections.defaultdict(list)
for e in figs:
    p = e["properties"]
    if p["unit"] == "killed" and p["scope"] == "national" and p.get("as_of", "") >= "2025-09-01": ser[p["as_of"]].append((p["figure"], p["as_of_basis"]))
for d in sorted(ser): L.append(f"| {d} | {', '.join(str(f) for f in sorted({x[0] for x in ser[d]}))} | {', '.join(sorted({x[1] for x in ser[d]}))} |")
nod = [e for e in figs if not e["properties"].get("as_of")]
L += ["", "Undated: " + "; ".join(f"{e['id'][6:]} ({fmt(e['properties']['figure'])} {e['properties']['unit']})" for e in nod), ""]
L += ["## Uncertain cases (judgement calls)", ""] + [f"- `{k}`: {m}" for k, m in rev["uncertain"]]
L += ["", "## Casualty-figure claims left without a figure", ""] + [f"- `{k}`: {m}" for k, m in rev["skipped"]]
L += ["", "Other claims with digits that were not given a figure: dates, counts of signatories, pages, petitions, poll votes, Discord attendance, percentages and prize or relief amounts (about 100 of the 116 non-casualty-figure claims containing digits)."]
open(f"{os.path.dirname(HERE)}/figures-report.md", "w").write("\n".join(L) + "\n")
print(len(figs), len(dis))
