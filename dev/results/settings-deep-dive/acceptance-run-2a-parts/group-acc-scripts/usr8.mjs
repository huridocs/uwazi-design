import { launch, open, S, shot } from "./lib.mjs";
import { watch, mk } from "./rec.mjs";
const { rec, save } = mk("usr8");
const b = await launch(); const consoleErrs = watch(b);
const norm = (s) => s.replace(/\s+/g, " ").trim();
const DLG = '[role=dialog]:not([inert] *)';
const rowOf = (p, n) => S(p).locator("[data-part=row]").filter({ hasText: n }).first();
const { page: p } = await open(b, "users");
const dlg = async (who, label) => { await rowOf(p, who).getByRole("button", { name: "Delete " + who }).click({ force: true }); await p.waitForTimeout(350); const t = norm(await p.locator(DLG).last().innerText()); if (label === "shot") await shot(p, "X-05"); await p.keyboard.press("Escape"); await p.waitForTimeout(250); return t; };
const usedUser = await dlg("mlopez");
const unusedUser = await dlg("tbuergenthal", "shot");
await p.getByRole("tab", { name: /Groups/ }).click(); await p.waitForTimeout(300);
const usedGroup = await dlg("Litigation");
await p.getByRole("button", { name: "Add group" }).click(); await p.waitForTimeout(300);
await S(p).getByPlaceholder("e.g. Litigation").fill("Empty one"); await p.locator("footer").last().getByRole("button").last().click(); await p.waitForTimeout(400);
const unusedGroup = await dlg("Empty one");
const usedOk = /Litigation/.test(usedUser) && /2 members lose this group/.test(usedGroup);
const unusedOk = /nothing else|Nothing else/i.test(unusedUser) && /nothing else|Nothing else|no members/i.test(unusedGroup);
rec("X-05", usedOk && unusedOk ? "PASS" : "FAIL", `Used user: "${usedUser}"; used group: "${usedGroup}" (both state what changes); unused user (no group): "${unusedUser}" (no "nothing else changes" statement); unused group: "${unusedGroup}" ("no members" implies it)`, "X-05.png");
rec("USR8-console", consoleErrs.length ? "FAIL" : "PASS", JSON.stringify(consoleErrs));
save(); await b.close();
