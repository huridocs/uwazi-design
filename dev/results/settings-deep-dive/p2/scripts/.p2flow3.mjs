import { chromium } from "playwright";
const OUT = "/Users/juanmnl/Developer/huridocs/uwazi_app/dev/results/settings-deep-dive/p2/flow";
const theme = process.argv[2] || "light";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage(); page.setDefaultTimeout(5000);
const log = []; page.on("pageerror", (e) => log.push("PAGEERROR " + e.message));
await page.addInitScript((theme) => { if (!sessionStorage.getItem("p2")) { sessionStorage.setItem("p2","1"); sessionStorage.setItem("uwazi:appView", JSON.stringify("settings")); localStorage.setItem("theme", theme);} }, theme);
await page.goto("http://localhost:1431/", { waitUntil: "networkidle" });
const nav = async (l) => { await page.getByRole("navigation", { name: "Settings navigation" }).getByRole("button", { name: l, exact: true }).click(); await page.waitForTimeout(300); };
const shot = async (n) => { await page.waitForTimeout(400); await page.screenshot({ path: `${OUT}/${theme}-${n}.png` }); };
const step = async (name, fn) => { try { await fn(); log.push("OK   " + name); } catch (e) { log.push("FAIL " + name + ": " + e.message.split("\n")[0]); await shot("FAIL3-" + name.replace(/\W+/g, "_")); } };
const openDrawerUndo = async (tag) => {
  await page.getByRole("button", { name: /^Notifications/ }).click();
  await shot(tag + "-drawer");
  await page.getByRole("button", { name: /Undo/ }).first().click();
  await page.keyboard.press("Escape");
};
await (async()=>{})("reltype move and delete, then undo", async () => {
  await nav("Relationship types");
  const row = page.getByRole("row").filter({ hasText: "Mentions" });
  await row.hover(); await row.getByRole("button", { name: /^Delete / }).click();
  const d = page.locator('[role="dialog"]').last();
  await d.getByRole("button", { name: /Choose a type/ }).click();
  await page.getByRole("option", { name: "Cites" }).click();
  await shot("22-reltype-target-chosen");
  await d.getByRole("button", { name: "Move and delete" }).click();
  await page.waitForTimeout(300);
  const after = await page.getByRole("row").filter({ hasText: "Cites" }).innerText();
  log.push("     Cites after move: " + after.replace(/\s+/g, " "));
  await shot("23-reltype-moved");
  await openDrawerUndo("24-reltype");
  await page.waitForTimeout(300);
  const back = await page.getByRole("row").filter({ hasText: "Mentions" }).count();
  const cites = await page.getByRole("row").filter({ hasText: "Cites" }).innerText();
  log.push(`     after undo: Mentions rows=${back}; Cites: ${cites.replace(/\s+/g, " ")}`);
  await shot("25-reltype-undone");
});
await step("thesaurus value remove, undo from drawer", async () => {
  await nav("Thesauri");
  await page.getByText("Regions", { exact: true }).click();
  await page.waitForTimeout(300);
  const cnt = () => page.getByRole("textbox", { name: "Item label" }).count(); const before = await cnt();
  const first = page.locator('div.group').filter({ has: page.locator('input[value="Caribbean"]') }).first();
  await first.hover(); await first.getByRole("button", { name: /^Delete / }).click();
  const mid = await cnt(); await shot("26a-value-removed");
  await openDrawerUndo("26-thesaurus");
  await page.waitForTimeout(300);
  const after = await cnt();
  log.push(`     items ${before} -> ${mid} -> ${after}`);
  await shot("27-thesaurus-undone");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
});
await step("activity log", async () => { await nav("Activity log"); await shot("28-activity-log"); });
console.log(log.join("\n")); await browser.close();
